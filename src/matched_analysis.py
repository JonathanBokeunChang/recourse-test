"""Within-factor matched comparison and noise-corrected flip rates.

The headline cited-vs-placebo gap conflates two things: whether citation predicts
pivotality, and which factor happened to be repaired (repair operators differ in
strength, and cited/placebo draws have different factor mixes). The matched
comparison holds the factor fixed: for each reason code, the flip rate when that
code was CITED versus when the SAME code was repaired as a PLACEBO on denials
that did not cite it. Any residual gap cannot be a repair-strength artifact.

Also reports McNemar's test (cited and placebo are measured on the same denials,
so Fisher's exact is the wrong test) and flip rates net of the no-repair control.
"""
import json
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np
from scipy import stats as sps

RES = Path(__file__).resolve().parent.parent / "results"
sys.path.insert(0, str(Path(__file__).parent))
from german import REASONS

# short labels: the full Reg B wording overflows a single column
SHORT = {
    "R1": "Checking balance", "R2": "Credit history", "R3": "Savings",
    "R4": "Employment", "R5": "Loan amount", "R6": "Loan duration",
    "R7": "Installment burden", "R8": "Collateral", "R9": "Other plans",
    "R10": "Existing credits", "R11": "No guarantor", "R12": "Housing",
}
LABEL = {k: SHORT.get(k, v[0]) for k, v in REASONS.items()}


def analyze(run):
    p = RES / f"{run}.json"
    if not p.exists():
        return None
    cases = json.load(open(p))["cases"]
    done = [c for c in cases.values() if "flip_cited" in c]
    if not done:
        return None

    # cited: flip rate when a code is the stated principal reason.
    # uncited: flip rate when the SAME code is repaired on a denial that did not
    # cite it -- from the full placebo sweep, which repairs every adverse uncited
    # factor rather than one sampled per denial.
    cited = defaultdict(list)
    placebo = defaultdict(list)
    for c in done:
        if c["codes"]:
            cited[c["codes"][0]].append(c["flip_cited"])
        for code, f in c.get("sweep", {}).items():
            placebo[code].append(f)
        if not c.get("sweep") and c.get("placebo_code") and c.get("flip_placebo") is not None:
            placebo[c["placebo_code"]].append(c["flip_placebo"])

    matched = {}
    for code in sorted(set(cited) & set(placebo)):
        if len(cited[code]) >= 10 and len(placebo[code]) >= 10:
            matched[code] = {
                "cited": float(np.mean(cited[code])), "n_cited": len(cited[code]),
                "placebo": float(np.mean(placebo[code])), "n_placebo": len(placebo[code])}

    # McNemar on the paired cited/placebo outcomes
    both = [c for c in done if c.get("flip_placebo") is not None]
    b = sum(1 for c in both if c["flip_cited"] and not c["flip_placebo"])
    cc = sum(1 for c in both if not c["flip_cited"] and c["flip_placebo"])
    mcnemar = sps.binomtest(b, b + cc, 0.5) if (b + cc) else None

    sweep_all = [f for c in done for f in c.get("sweep", {}).values()]
    noop = [c["flip_noop"] for c in done if "flip_noop" in c]
    out = {
        "n": len(done),
        "flip_cited": float(np.mean([c["flip_cited"] for c in done])),
        "flip_placebo": float(np.mean([c["flip_placebo"] for c in both])),
        "flip_noop": float(np.mean(noop)) if noop else None,
        "n_noop": len(noop),
        "mcnemar_b": b, "mcnemar_c": cc,
        "mcnemar_p": mcnemar.pvalue if mcnemar else None,
        "matched": matched,
        "sweep_flip": float(np.mean(sweep_all)) if sweep_all else None,
        "n_sweep": len(sweep_all),
    }
    return out


def to_tex(res):
    """Matched-comparison table."""
    rows = []
    for code, m in sorted(res["matched"].items(),
                          key=lambda x: -(x[1]["cited"] - x[1]["placebo"])):
        rows.append(f"{LABEL[code]} & {m['cited']:.2f} ({m['n_cited']}) & "
                    f"{m['placebo']:.2f} ({m['n_placebo']}) & "
                    f"${m['cited'] - m['placebo']:+.2f}$ \\\\")
    body = "\n".join(rows)
    return ("% AUTO-GENERATED by matched_analysis.py\n\\begin{table}[t]\n"
            "\\caption{Matched within-factor comparison: flip rate when a factor is the "
            "\\emph{cited} principal reason versus when the \\emph{same} factor is repaired "
            "as a placebo on denials that did not cite it ($n$ in parentheses). Holding the "
            "repaired factor fixed removes repair-strength and factor-mix confounds; the "
            "surviving gap is citation's causal information.}\n"
            "\\label{tab:between}\n\\small\n\\begin{tabular}{lccc}\n\\toprule\n"
            "Factor & cited & as placebo & $\\Delta$ \\\\\n\\midrule\n"
            + body + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")


if __name__ == "__main__":
    best = None
    for run in ["s1_haiku_n260_s3", "s1_haiku_n200_s4", "s1_sonnet_n150_s3"]:
        r = analyze(run)
        if not r:
            continue
        print(f"\n{run}: n={r['n']} cited={r['flip_cited']:.3f} "
              f"placebo={r['flip_placebo']:.3f} sweep={r['sweep_flip']} (n={r['n_sweep']}) "
              f"noop={r['flip_noop']} (n={r['n_noop']})")
        print(f"  McNemar b={r['mcnemar_b']} c={r['mcnemar_c']} p={r['mcnemar_p']}")
        for code, m in sorted(r["matched"].items()):
            print(f"  {code:4s} cited {m['cited']:.2f} (n={m['n_cited']:3d}) | "
                  f"placebo {m['placebo']:.2f} (n={m['n_placebo']:3d})")
        if best is None:
            best = r
    if best and best["matched"]:
        (Path(__file__).resolve().parent.parent / "paper" / "matched_gen.tex").write_text(to_tex(best))
        print("\nwrote matched_gen.tex")


def emit_macros(res, run):
    """Every number the prose quotes, generated from the run so it cannot drift."""
    import math
    from collections import defaultdict
    cases = json.load(open(RES / f"{run}.json"))["cases"]
    done = [c for c in cases.values() if "flip_cited" in c]
    same_dec = [c for c in done if c.get("para_decision") == "DENY"]
    top_stable = [c for c in same_dec if c["codes"] and c.get("para_codes")
                  and c["codes"][0] == c["para_codes"][0]]
    set_stable = [c for c in same_dec if set(c["codes"]) == set(c.get("para_codes", []))]
    per_cited, per_unc = defaultdict(list), defaultdict(list)
    for c in done:
        if c["codes"]:
            per_cited[c["codes"][0]].append(c["flip_cited"])
        for code, f in c.get("sweep", {}).items():
            per_unc[code].append(f)
    unc_rates = {k: float(np.mean(v)) for k, v in per_unc.items() if len(v) >= 20}
    # smallest integer exp with p < 10^exp (floor alone gives p >= 10^exp)
    exp = int(math.floor(math.log10(res["mcnemar_p"]))) + 1 if res["mcnemar_p"] else 0
    m = [
        "% AUTO-GENERATED by matched_analysis.py",
        "\\makeatletter",
        f"\\providecommand{{\\NSweep}}{{{res['n_sweep']}}}",
        f"\\providecommand{{\\McNemarExp}}{{{exp}}}",
        f"\\providecommand{{\\McNemarB}}{{{res['mcnemar_b']}}}",
        f"\\providecommand{{\\McNemarC}}{{{res['mcnemar_c']}}}",
        f"\\providecommand{{\\TopStable}}{{{100*len(top_stable)/max(len(same_dec),1):.0f}\\%}}",
        f"\\providecommand{{\\SetStable}}{{{100*len(set_stable)/max(len(same_dec),1):.0f}\\%}}",
        f"\\providecommand{{\\UncitedMin}}{{{100*min(unc_rates.values()):.0f}\\%}}",
        f"\\providecommand{{\\UncitedMax}}{{{100*max(unc_rates.values()):.0f}\\%}}",
        f"\\providecommand{{\\GapPoints}}{{{100*(res['flip_cited']-res['flip_placebo']):.0f}}}",
        f"\\providecommand{{\\NetCited}}{{{100*(res['flip_cited']-(res['flip_noop'] or 0)):.0f}}}",
        f"\\providecommand{{\\NetPlacebo}}{{{100*(res['flip_placebo']-(res['flip_noop'] or 0)):.0f}}}",
    ]
    for code, v in sorted(per_cited.items()):
        if len(v) >= 10:
            name = {"R1": "Chk", "R2": "Hist", "R3": "Sav", "R4": "Emp"}.get(code)
            if name:
                m.append(f"\\providecommand{{\\Cited{name}}}{{}}\\renewcommand{{\\Cited{name}}}{{{100*np.mean(v):.0f}\\%}}")
    m.append("\\makeatother")
    (Path(__file__).resolve().parent.parent / "paper" / "macros_gen.tex").write_text(
        "\n".join(x.replace("providecommand", "renewcommand") if x.startswith("\\provide") else x for x in m) + "\n")
    print("wrote macros_gen.tex")


if __name__ == "__main__":
    r = analyze("s1_haiku_n260_s3")
    if r:
        emit_macros(r, "s1_haiku_n260_s3")
