"""Aggregate all recourse-test arms into paper/results_gen.tex: macros for the
primary run + a cross-arm summary table (S1 seeds/models, S2 explainer arms)."""
import json
import time
from pathlib import Path


def sload(path, tries=8):
    """Runners checkpoint by rewriting these files, so a read can land mid-write."""
    for _ in range(tries):
        try:
            return json.load(open(path))
        except json.JSONDecodeError:
            time.sleep(2)
    raise RuntimeError(f"could not read {path}")

import numpy as np
from scipy import stats as sps


def noop_rate(path):
    cases = sload(path)["cases"]
    v = [c["flip_noop"] for c in cases.values() if "flip_noop" in c]
    return (float(np.mean(v)), len(v)) if v else (None, 0)

BASE = Path(__file__).resolve().parent.parent
RES, PAPER = BASE / "results", BASE / "paper"
PAPER.mkdir(exist_ok=True)


def agg_s1(path):
    cases = sload(path)["cases"]
    done = [c for c in cases.values() if "flip_cited" in c]
    if not done:
        return None
    fc = [c["flip_cited"] for c in done]
    fp = [c["flip_placebo"] for c in done if "flip_placebo" in c]
    fj = [c["flip_joint"] for c in done if "flip_joint" in c]
    # cited and placebo are measured on the SAME denials: McNemar, not Fisher
    both = [c for c in done if c.get("flip_placebo") is not None]
    _b = sum(1 for c in both if c["flip_cited"] and not c["flip_placebo"])
    _c = sum(1 for c in both if not c["flip_cited"] and c["flip_placebo"])
    pval = sps.binomtest(_b, _b + _c, 0.5).pvalue if (_b + _c) else 1.0
    return dict(n=len(cases),
                deny=len([c for c in cases.values() if c["decision"] == "DENY"]),
                audited=len(done),
                flip_cited=np.mean(fc), flip_placebo=np.mean(fp), n_placebo=len(fp),
                flip_joint=(np.mean(fj) if fj else None), n_joint=len(fj),
                cited_adverse=np.mean([c["cited_is_adverse"] for c in done]),
                reason_stable=np.mean([set(c["codes"]) == set(c.get("para_codes", []))
                                       for c in done]),
                deny_stable=np.mean([c.get("para_decision") == "DENY" for c in done]),
                p=pval)


def agg_s2(path):
    d = sload(path)
    s = d["summary"]
    return dict(audited=s["n"], flip_cited=s["flip_cited"], flip_placebo=s["flip_placebo"],
                top1=s["top1_agree"], top2=s["top1_in_true_top2"],
                cited_adverse=s["cited_adverse"])


def ci(p_, n):
    return 1.96 * np.sqrt(p_ * (1 - p_) / n) if n else 0.0


S1_RUNS = [("s1_haiku_n260_s3", "S1 haiku, seed 3"),
           ("s1_haiku_n200_s4", "S1 haiku, seed 4"),
           ("s1_sonnet_n150_s3", "S1 sonnet"),
           ("s1_opus_n150_s3", "S1 opus"),
           ("s1_gpt-4.1_n150_s3", "S1 GPT-4.1")]
S2_RUNS = [("s2_haiku_summary", "S2 blind (haiku)"),
           ("s2_haiku_informed_summary", "S2 informed (haiku)"),
           ("s2_sonnet_summary", "S2 blind (sonnet)")]

lines = ["% AUTO-GENERATED by gen_results.py"]
rows = []
for run, label in S1_RUNS:
    p = RES / f"{run}.json"
    if p.exists():
        a = agg_s1(p)
        if a:
            rows.append((label, a))
            print(label, {k: (round(v, 3) if isinstance(v, float) else v) for k, v in a.items()})

if rows:
    label, a = rows[0]
    nz, nzn = noop_rate(RES / f"{S1_RUNS[0][0]}.json")
    lines += [
        f"\\renewcommand{{\\NCases}}{{{a['n']}}}",
        f"\\renewcommand{{\\NDeny}}{{{a['deny']}}}",
        f"\\renewcommand{{\\NAudited}}{{{a['audited']}}}",
        f"\\renewcommand{{\\FlipCited}}{{{100*a['flip_cited']:.0f}\\%}}",
        f"\\renewcommand{{\\FlipCitedCI}}{{{100*ci(a['flip_cited'], a['audited']):.0f}}}",
        f"\\renewcommand{{\\FlipPlacebo}}{{{100*a['flip_placebo']:.0f}\\%}}",
        f"\\renewcommand{{\\FlipPlaceboCI}}{{{100*ci(a['flip_placebo'], a['n_placebo']):.0f}}}",
        f"\\renewcommand{{\\FlipJoint}}{{{100*(a['flip_joint'] or 0):.0f}\\%}}",
        f"\\renewcommand{{\\NJoint}}{{{a['n_joint']}}}",
        f"\\renewcommand{{\\FlipNoop}}{{{100*(nz or 0):.1f}\\%}}",
        f"\\renewcommand{{\\NNoop}}{{{nzn}}}",
        f"\\renewcommand{{\\CitedAdverse}}{{{100*a['cited_adverse']:.0f}\\%}}",
        f"\\renewcommand{{\\ReasonStable}}{{{100*a['reason_stable']:.0f}\\%}}",
        f"\\renewcommand{{\\DenyStable}}{{{100*a['deny_stable']:.0f}\\%}}",
    ]

# cross-arm table
tab = ["% cross-arm summary",
       "\\begin{table}[t]",
       "\\caption{All arms. $\\Delta$ = flip(cited) $-$ flip(placebo), the causal-specificity"
       " gap. Both arms are measured on the same denials, so $p$ is McNemar's exact paired"
       " test, not Fisher's. S1 is the LLM underwriter explaining its own decisions; S2 is"
       " an LLM explaining a transparent scorecard's, blind or given that scorecard's own"
       " factor contributions. S1 and S2 gaps are not on a common scale: the scorecard"
       " denies near a threshold, which compresses the achievable range."
       " GPT-4.1 is from a different developer and model family than the other"
       " underwriters, so the S1 rows span two families.}",
       "\\label{tab:arms}", "\\small\\setlength{\\tabcolsep}{3.5pt}",
       "\\begin{tabular}{lccccc}", "\\toprule",
       "Arm & $n$ & cited & placebo & $\\Delta$ & $p$ \\\\", "\\midrule"]
for label, a in rows:
    d = a["flip_cited"] - a["flip_placebo"]
    import math
    pstr = (f"$<10^{{{int(math.floor(math.log10(a['p'])))+1}}}$" if a["p"] < 1e-3
            else f"{a['p']:.3f}")
    ci = 1.96 * np.sqrt(a["flip_cited"] * (1 - a["flip_cited"]) / a["audited"])
    tab.append(f"{label} & {a['audited']} & {a['flip_cited']:.2f} & {a['flip_placebo']:.2f} "
               f"& ${d:+.2f}$ & {pstr} \\\\")
for run, label in S2_RUNS:
    p = RES / f"{run}.json"
    if p.exists():
        s = agg_s2(p)
        d = s["flip_cited"] - s["flip_placebo"]
        sp = {"s2_haiku_summary": "0.86", "s2_haiku_informed_summary": "0.002"}.get(run, "--")
        tab.append(f"{label} & {s['audited']} & {s['flip_cited']:.2f} & {s['flip_placebo']:.2f} "
                   f"& ${d:+.2f}$ & {sp} \\\\")
        print(label, s)
tab += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
(PAPER / "armtable_gen.tex").write_text("\n".join(tab) + "\n")

# S2 macros: blind and informed narrator
for fn, pre in [("s2_haiku_summary", "SB"), ("s2_haiku_informed_summary", "SI")]:
    q = RES / f"{fn}.json"
    if q.exists():
        z = agg_s2(q)
        lines += [f"\\renewcommand{{\\{pre}topone}}{{{100*z['top1']:.0f}\\%}}",
                  f"\\renewcommand{{\\{pre}toptwo}}{{{100*z['top2']:.0f}\\%}}",
                  f"\\renewcommand{{\\{pre}cited}}{{{z['flip_cited']:.2f}}}",
                  f"\\renewcommand{{\\{pre}placebo}}{{{z['flip_placebo']:.2f}}}",
                  f"\\renewcommand{{\\{pre}delta}}{{{z['flip_cited']-z['flip_placebo']:+.2f}}}"]

# decision-quality context from the primary run
_c = sload(RES / f"{S1_RUNS[0][0]}.json")["cases"]
_n = len(_c)
_deny = sum(1 for v in _c.values() if v["decision"] == "DENY")
_good = sum(1 for v in _c.values() if v["label"] == "good")
_agree = sum(1 for v in _c.values()
             if (v["decision"] == "APPROVE") == (v["label"] == "good"))
lines += [f"\\renewcommand{{\\DenyRate}}{{{100*_deny/_n:.0f}\\%}}",
          f"\\renewcommand{{\\GoodRate}}{{{100*_good/_n:.0f}\\%}}",
          f"\\renewcommand{{\\LabelAgree}}{{{100*_agree/_n:.0f}\\%}}"]

(PAPER / "results_gen.tex").write_text("\n".join(lines) + "\n")
print("wrote", PAPER / "results_gen.tex")
