"""Per-code pivotality and citation concentration.

Two quantities per reason code, pooled over the two haiku underwriter samples:
how often a denial flips when that code is the cited principal reason, and how
often it flips when the same code is repaired on a denial that did NOT cite it
(the uncited sweep). Reporting both for every code -- including the codes that
are never cited -- shows which part of the menu the system actually uses.
"""
import json
import sys
from collections import defaultdict, Counter
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent
RES, PAPER = BASE / "results", BASE / "paper"
sys.path.insert(0, str(Path(__file__).parent))
from german import REASONS  # noqa: E402

RUNS = ["s1_haiku_n260_s3", "s1_haiku_n200_s4"]
SHORT = {
    "R1": "Checking balance", "R2": "Credit history", "R3": "Savings",
    "R4": "Employment", "R5": "Loan amount", "R6": "Loan duration",
    "R7": "Installment burden", "R8": "Collateral", "R9": "Other plans",
    "R10": "Existing credits", "R11": "No guarantor", "R12": "Housing",
}
MIN_N = 10  # below this an estimate is reported but not used for the range claim


def main():
    cited = defaultdict(list)     # flips when this code is the principal reason
    uncited = defaultdict(list)   # flips when repaired as a non-cited adverse factor
    cite_count = Counter()        # citations in any position
    principal = Counter()         # citations in first position
    ndenials = 0
    for run in RUNS:
        p = RES / f"{run}.json"
        if not p.exists():
            continue
        for v in json.load(open(p))["cases"].values():
            if "flip_cited" not in v or not v.get("codes"):
                continue
            ndenials += 1
            principal[v["codes"][0]] += 1
            for c in v["codes"]:
                cite_count[c] += 1
            cited[v["codes"][0]].append(v["flip_cited"])
            for code, val in (v.get("sweep") or {}).items():
                if val is not None:
                    uncited[code].append(val)

    codes = sorted(REASONS, key=lambda c: int(c[1:]))
    out = ["% AUTO-GENERATED by percode.py", "\\begin{table}[t]",
           "\\caption{Per-code pivotality across the full menu, pooled over both haiku "
           "underwriter samples ($n$ in parentheses). \\emph{cited} is the flip rate when "
           "the code is the principal reason; \\emph{uncited} is the flip rate when the "
           "same code is repaired on a denial that did not cite it. \\emph{princ.} counts "
           "denials naming the code first. Two patterns: the cited column is empty for "
           "most of the menu, because the underwriter draws its principal reasons from a "
           "small part of it; and the uncited column is uniformly low but never zero, "
           "which is why a placebo arm is needed rather than assumed.}",
           "\\label{tab:percode}", "\\small\\setlength{\\tabcolsep}{4pt}",
           "\\begin{tabular}{llrcc}", "\\toprule",
           "Code & Factor & princ. & cited & uncited \\\\", "\\midrule"]
    for c in codes:
        cv, uv = cited.get(c, []), uncited.get(c, [])
        cs = f"{sum(cv)/len(cv):.2f} ({len(cv)})" if cv else "--"
        us = f"{sum(uv)/len(uv):.2f} ({len(uv)})" if uv else "--"
        out.append(f"\\texttt{{{c}}} & {SHORT[c]} & {principal.get(c,0)} & {cs} & "
                   f"{us} \\\\")
    out += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    (PAPER / "percode_gen.tex").write_text("\n".join(out))

    n_principal = len([c for c in codes if principal.get(c, 0) > 0])
    total_cites = sum(cite_count.values())
    top3 = sum(v for _, v in cite_count.most_common(3))
    big_unc = {c: sum(v) / len(v) for c, v in uncited.items() if len(v) >= MIN_N}
    lo, hi = min(big_unc.values()), max(big_unc.values())
    lo_c = min(big_unc, key=big_unc.get)
    hi_c = max(big_unc, key=big_unc.get)
    print(f"denials={ndenials} codes used as principal={n_principal}/{len(codes)}")
    print(f"top-3 share of all citations: {top3}/{total_cites} = {top3/total_cites:.1%}")
    print(f"uncited flip range (n>={MIN_N}): {lo:.2f} ({lo_c}) .. {hi:.2f} ({hi_c})")

    macros = [
        "% AUTO-GENERATED by percode.py",
        f"\\renewcommand{{\\NPrincipalCodes}}{{{n_principal}}}",
        f"\\renewcommand{{\\NMenuCodes}}{{{len(codes)}}}",
        f"\\renewcommand{{\\TopThreeShare}}{{{100*top3/total_cites:.0f}\\%}}",
        f"\\renewcommand{{\\UncitedLo}}{{{100*lo:.0f}\\%}}",
        f"\\renewcommand{{\\UncitedHi}}{{{100*hi:.0f}\\%}}",
        f"\\renewcommand{{\\UncitedLoName}}{{{SHORT[lo_c].lower()}}}",
        f"\\renewcommand{{\\UncitedHiName}}{{{SHORT[hi_c].lower()}}}",
        "",
    ]
    (PAPER / "percodemacros_gen.tex").write_text("\n".join(macros))
    print("wrote percode_gen.tex, percodemacros_gen.tex")


if __name__ == "__main__":
    main()
